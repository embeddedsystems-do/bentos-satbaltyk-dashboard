// Kolejnosc = kolejnosc w przelaczniku jezyka.
export const LANGUAGES = ["pl", "en", "sv"];
const LOCALES = { pl: "pl-PL", en: "en-GB", sv: "sv-SE" };

const I18nContext = createContext(null);

function interpolate(value, vars) {
  return value.replace(/\{(\w+)\}/g, (_, key) => vars[key] ?? `{${key}}`);
}

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const stored = localStorage.getItem("bentos-language");
    return LANGUAGES.includes(stored) ? stored : "pl";
  });

  useEffect(() => {
    localStorage.setItem("bentos-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    locale: LOCALES[language],
    t(key, vars = {}) {
      return interpolate(translations[language][key] ?? translations.pl[key] ?? key, vars);
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
